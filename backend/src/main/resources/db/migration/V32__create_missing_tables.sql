-- Creates tables currently missing from seeds_indent_replica_1 but mapped in JPA entities

-- 1. Create tbl_audit_log
CREATE TABLE IF NOT EXISTS tbl_audit_log (
    audit_id INT AUTO_INCREMENT PRIMARY KEY,
    audit_action VARCHAR(100) NOT NULL,
    audit_entity_type VARCHAR(100),
    audit_entity_id VARCHAR(100),
    audit_user_id INT,
    audit_username VARCHAR(100),
    audit_ip_address VARCHAR(45),
    audit_timestamp DATETIME(6) NOT NULL,
    audit_details TEXT,
    audit_status VARCHAR(50)
);

-- 2. Create tbl_goods_receipt
